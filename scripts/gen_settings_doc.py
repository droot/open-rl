"""Render the openrl.* settings table for the skill from the server's OpenAPI document.

  uv run --extra cpu python scripts/gen_settings_doc.py          # rewrite skills/openrl/references/settings.md
  uv run --extra cpu python scripts/gen_settings_doc.py --check  # exit 1 if the file is stale

The table comes from components.schemas.OpenRLSettings, the JSON Schema a
running server publishes at /openapi.json and as openrl.settings in
get_server_capabilities. tests/test_skill_docs.py runs the check, so the
table cannot drift from class Settings (design 016, section 5.5).
"""

import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from server.api_server import app  # noqa: E402

TARGET = ROOT / "skills" / "openrl" / "references" / "settings.md"

HEADER = """# openrl.* settings

Generated by `scripts/gen_settings_doc.py` from `components.schemas.OpenRLSettings`
in the server's OpenAPI document; do not edit by hand. A running server publishes
the same schema at `/openapi.json` and as `openrl.settings` in
`GET /api/v1/get_server_capabilities`, so an agent can read the live deployment's
settings without this file.

Pass settings as `user_metadata` on `create_session` or `create_model`, or as
`TINKER_TAGS=openrl.key=value,openrl.other=value` in the client's environment.
Model settings override session settings. Values are strings on the wire
(`"true"`, `"8"`); an unknown `openrl.` key or a bad value is a 400 that names
the setting.

```python
client = tinker.ServiceClient(base_url=..., user_metadata={"openrl.fine_tuning_type": "full"})
```

"""

TYPE_NAMES = {"integer": "int", "boolean": "bool"}


def settings_schema() -> dict[str, Any]:
  return app.openapi()["components"]["schemas"]["OpenRLSettings"]


def fmt(value) -> str:
  if value is None:
    return "unset"
  if isinstance(value, bool):
    return str(value).lower()
  return f"`{value}`"


def row(name: str, prop: dict[str, Any]) -> str:
  # An optional setting arrives as anyOf [X, null]; show X.
  options = [option for option in prop.get("anyOf", [prop]) if option.get("type") != "null"]
  schema = options[0] if len(options) == 1 else {"type": "string"}
  kind = TYPE_NAMES.get(schema.get("type"), "string")
  values = ", ".join(f"`{v}`" for v in schema["enum"]) if "enum" in schema else ""
  if "minimum" in schema or "maximum" in schema:
    values = f"{schema.get('minimum', '')} to {schema.get('maximum', '')}"
  return f"| `{name}` | {kind} | {fmt(prop.get('default'))} | {values} | {prop.get('description', '')} |"


def render() -> str:
  rows = ["| Setting | Type | Default | Values | Description |", "|---|---|---|---|---|"]
  rows += [row(name, prop) for name, prop in settings_schema()["properties"].items()]
  return HEADER + "\n".join(rows) + "\n"


def main() -> None:
  text = render()
  if "--check" in sys.argv:
    current = TARGET.read_text() if TARGET.exists() else ""
    if current != text:
      print(f"{TARGET.relative_to(ROOT)} is stale; run scripts/gen_settings_doc.py", file=sys.stderr)
      sys.exit(1)
    print("settings.md is current")
    return
  TARGET.parent.mkdir(parents=True, exist_ok=True)
  TARGET.write_text(text)
  print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
  main()
